#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md for the libraries statically linked into the extension.

License texts come from the pinned vcpkg packages (vcpkg_installed/<triplet>/share/<port>/copyright),
NOTICE files from each project's repository at the pinned release tag. Run after `make release`
whenever VCPKG_COMMIT or vcpkg.json changes:

  python3 scripts/third_party_notices.py [build/release/vcpkg_installed]
"""
import hashlib
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
installed = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'build/release/vcpkg_installed'
triplet = next(p for p in installed.iterdir() if p.is_dir() and p.name != 'vcpkg')
ports = {}
for listing in (installed / 'vcpkg/info').glob('*.list'):
    name, version, _ = listing.stem.split('_', 2)
    if not name.startswith('vcpkg-'):  # build helpers, not linked
        ports[name] = version

# Upstream repositories and tags of the ports that publish a NOTICE file (Apache-2.0 attribution).
NOTICES = {
    'aws-sdk-cpp': ('aws/aws-sdk-cpp', '{v}', 'NOTICE.txt'),
    'aws-crt-cpp': ('awslabs/aws-crt-cpp', 'v{v}', 'NOTICE'),
    's2n': ('aws/s2n-tls', 'v{v}', 'NOTICE'),
    'aws-checksums': ('awslabs/aws-checksums', 'v{v}', 'NOTICE'),  # none published; kept in case it appears
}
for port in ports:
    if port.startswith('aws-c-'):
        NOTICES[port] = (f'awslabs/{port}', 'v{v}', 'NOTICE')
DESCRIPTION = {
    'aws-sdk-cpp': 'AWS SDK for C++ (core and S3 client)',
    'aws-crt-cpp': 'AWS Common Runtime for C++',
    's2n': 's2n-tls (TLS on Linux)',
    'openssl': 'OpenSSL (TLS, SHA-256)',
    'curl': 'curl (HTTP client of the AWS SDK)',
    'zlib': 'zlib (compression)',
    'sqlite3': 'SQLite (metadata store)',
}


def notice(port, version):
    if port not in NOTICES:
        return None
    repo, tag, path = NOTICES[port]
    url = f'https://raw.githubusercontent.com/{repo}/{tag.format(v=version)}/{path}'
    r = subprocess.run(['curl', '-sSL', '-w', '\n%{http_code}', url], capture_output=True, text=True)
    body, _, status = r.stdout.rpartition('\n')
    if r.returncode == 0 and status == '404':
        return None  # the project publishes no NOTICE file
    if r.returncode or status != '200':
        raise SystemExit(f'Cannot fetch {url} (HTTP {status})')
    return body.strip()


duckdb_license = (ROOT / 'duckdb/LICENSE').read_text().strip()
duckdb_version = subprocess.run(['git', '-C', str(ROOT / 'duckdb'), 'describe', '--tags'], capture_output=True,
                                text=True).stdout.strip() or 'v1.5.6'
texts, users = {}, {}
for port in sorted(ports):
    text = (triplet / 'share' / port / 'copyright').read_text().strip()
    key = hashlib.sha256(' '.join(text.split()).encode()).hexdigest()
    texts[key] = text
    users.setdefault(key, []).append(port)

out = ['# Third-party notices', '',
       'Release builds of the `differential` extension statically link the following libraries,',
       f'pinned through vcpkg (`VCPKG_COMMIT` in the `Makefile`). Generated by',
       '`scripts/third_party_notices.py`; do not edit by hand.', '',
       '## DuckDB', '',
       f'The extension statically links DuckDB {duckdb_version} (MIT License) and the third-party code',
       'DuckDB bundles, whose license files are under `third_party/` in the DuckDB repository.', '',
       '```', duckdb_license, '```', '',
       '## vcpkg libraries', '',
       '| Library | Version | License |', '| --- | --- | --- |']
license_name = {}
for key, text in texts.items():
    head = text[:400]
    license_name[key] = ('Apache License 2.0' if 'Apache License' in head else
                         'curl license' if 'Daniel Stenberg' in head else
                         'zlib license' if 'Jean-loup Gailly' in head else
                         'Public domain' if 'Public Domain' in head else 'see below')
for port in sorted(ports):
    key = next(k for k, v in users.items() if port in v)
    out.append(f"| {DESCRIPTION.get(port, port)} | {ports[port]} | {license_name[key]} |")
out += ['', '## Notices', '']
for port in sorted(ports):
    text = notice(port, ports[port])
    if text:
        out += [f'### {port} {ports[port]}', '', '```', text, '```', '']
out += ['## License texts', '']
for key, text in texts.items():
    out += [f"### {license_name[key]}: {', '.join(users[key])}", '', '```', text, '```', '']
(ROOT / 'THIRD_PARTY_NOTICES.md').write_text('\n'.join(out))
print(f'Wrote THIRD_PARTY_NOTICES.md: {len(ports)} libraries, {len(texts)} distinct license texts')
